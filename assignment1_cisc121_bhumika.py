def solution(A, K):
    if len(A) == 0:  #Checking if the array is empty, if its empty return it as it is.
        return A

    #Calculating the effective number of rotations
    K = K % len(A)

    #Rotating the array to the right by K positions and storing it using return
    rotated_array = A[-K:] + A[:-K]

    return rotated_array

