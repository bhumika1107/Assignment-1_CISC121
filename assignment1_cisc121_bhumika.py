def solution(A):
  #Converting the array into a set so we can remove duplicates
  B=set(A)
  #Start checking from 1, since we need the smallest positive integer
  number=1

  #We keep going as long as the current number is present in the set
  while number in B:
    #If it's there, move on and check the next integer
    number=number+1

  #The loop stopped, so this is the first positive integer that is missing
  return number