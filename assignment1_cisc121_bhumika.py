"""#Problem 6- PermCheck"""

def solution(A):
    #Finding how many numbers are in the array
    n= len(A)
    #Converting the array into a set to remove duplicates
    #If the length stays the same, there were no repeated numbers
    no_repeats= len(set(A)) == n

    #Checking if the largest number in the array is equal to n
    biggest_num= max(A) == n

    #If there are no duplicates and the biggest number is n, the array must contain all numbers from 1 to n
    if no_repeats and biggest_num:
        return 1

    #Otherwise, the array is not a permutation
    return 0

